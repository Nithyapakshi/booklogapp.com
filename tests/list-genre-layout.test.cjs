const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const page = fs.readFileSync('app/books/page.tsx', 'utf8')
const row = page.slice(page.indexOf('function BookListRow('), page.indexOf('function generateBookColor'))
const css = fs.readFileSync('app/books/list-row.css', 'utf8')
test('phone title and author span the details area while stars stay right of genre', () => {
  assert.match(page, /import "\.\/list-row\.css"/)
  assert.match(row, /bl-list-row-rated/)
  assert.match(css, /max-width: 767px/)
  assert.match(css, /bl-list-title \{ grid-column: 2 \/ 4/)
  assert.match(css, /bl-list-author \{ grid-column: 2 \/ 4/)
  assert.match(css, /bl-list-stars \{ grid-column: 3; grid-row: 4/)
  assert.match(css, /bl-list-menu \{ position: absolute/)
})
test('full genre wraps without changing stored book or rating logic', () => {
  assert.match(row, /maxWidth: "100%"/)
  assert.match(row, /overflowWrap: "anywhere"/)
  assert.match(row, /\{book\.genre\}/)
  assert.match(row, /await updateRating\(book.id, star\)/)
})
